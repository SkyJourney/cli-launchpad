//! Single source of truth for backend error codes (`contracts/error-codes.json`).
//! Codes are `domain.reason`; legacy underscore codes live only in the contract's aliases.

/// A registered backend error code. The wire form is [`ErrorCode::as_str`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ErrorCode {
    AppDataReplaceBlocked,
    AppDataReplaceInProgress,
    AppExitDeferred,
    AppExiting,
    AppInternal,
    BackupIndexRefreshDiscarded,
    BackupRestoreInProgress,
    BlockingTimeout,
    ConfigImportInProgress,
    DbPoisoned,
    DirectoryInUse,
    ExecBusy,
    ExecPlanChanged,
    ExitImpactsChanged,
    ExitImpactsNotReported,
    ExitNoPendingRequest,
    ExitReportInvalid,
    ExitRequestMismatch,
    FileNotFound,
    FileNotRegular,
    FileNotUtf8,
    FilePermissionDenied,
    FileTooLarge,
    InternalLockPoisoned,
    InternalTaskFailed,
    LayoutCaseDuplicate,
    LayoutNameExists,
    LayoutPresetLimit,
    ProjectIdentityChanged,
    ProjectIdentityUnreadable,
    ProjectNotFound,
    PtyHandoffExpired,
    PtyHandoffInProgress,
    PtyHandoffTargetIsSource,
    PtyInputBackpressure,
    PtyInputUnavailable,
    PtyOwnerMismatch,
    PtySessionNotFound,
    PtySessionStarting,
    PtySessionsActive,
    WindowLabelInvalid,
    WindowMessageTooLarge,
    WindowNotAllowed,
}

